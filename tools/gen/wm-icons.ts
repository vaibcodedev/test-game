function render(mat: Mat, rows: string[]): PC {
  const pc = new PC(14, 14);
  const at = (x: number, y: number) => rows[y]?.[x] ?? ".";
  const filled = (x: number, y: number) => at(x, y) !== ".";
  const o = hex(mat.o);
  for (let y = -1; y <= 12; y++) for (let x = -1; x <= 12; x++) {
    const c = at(x, y);
    if (c === ".") { if (filled(x - 1, y) || filled(x + 1, y) || filled(x, y - 1) || filled(x, y + 1)) pc.set(x + 1, y + 1, o); continue; }
    if (c === "e") { pc.set(x + 1, y + 1, hex("#120a10")); continue; }
    if (c === "w") { pc.set(x + 1, y + 1, hex("#fff2b0")); continue; }
    const tl = !filled(x - 1, y) || !filled(x, y - 1), br = !filled(x + 1, y) || !filled(x, y + 1);
    const t = tl && !br ? 2 : br && !tl ? 0 : 1; // 2 свет, 1 середина, 0 тень
    let k: RGBA;
    if (c === "#") k = hex([mat.d, mat.m, mat.l][t]);
    else if (c === "a") k = shade(hex(mat.a), [0.72, 1, 1.28][t]);
    else k = hex(mat.b);
    pc.set(x + 1, y + 1, k);
  }
  return pc;
}
export function build(v: string, name: string): PC {
  const { mat, rows } = V[v][name];
  return render(mat, rows);
}

