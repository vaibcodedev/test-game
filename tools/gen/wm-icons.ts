/** Кнопка «Ко мне»: A — прицел (кольцо, риски, точка); B — компас-крест, север красный; C — кольцо с точкой. */
const ring = (kind: "A" | "B" | "C"): string[] => {
  const g: string[][] = Array.from({ length: 12 }, () => Array(12).fill("."));
  const set = (x: number, y: number, c = "#") => { if (x >= 0 && y >= 0 && x < 12 && y < 12) g[y][x] = c; };
  if (kind === "A") {
    for (let y = 0; y < 12; y++) for (let x = 0; x < 12; x++) { const d = Math.hypot(x - 5.5, y - 5.5); if (d > 3.3 && d < 4.6) set(x, y); }
    for (const i of [0, 1, 10, 11]) { set(5, i); set(6, i); set(i, 5); set(i, 6); }
    for (const [x, y] of [[5, 5], [6, 5], [5, 6], [6, 6]]) set(x, y, "a");
  } else if (kind === "B") {
    for (let i = 0; i < 12; i++) { const w = Math.abs(i - 5.5) < 2.5 ? 2 : 1; for (let k = 0; k < w; k++) { set(5 + (w === 2 ? k - 0 : 0) + (w === 2 ? 0 : 0), i, i < 6 ? "a" : "#"); set(6, i, i < 6 ? "a" : "#"); } }
    for (let i = 0; i < 12; i++) { if (i < 4 || i > 7) { set(i, 5); set(i, 6); } else { set(i, 5); set(i, 6); } }
    for (const [x, y] of [[5, 5], [6, 5]]) set(x, y, "a");
    set(5, 6, "w");
  } else {
    for (let y = 0; y < 12; y++) for (let x = 0; x < 12; x++) { const d = Math.hypot(x - 5.5, y - 5.5); if (d < 5.5 && d > 3.7) set(x, y); else if (d <= 2.4) set(x, y, "a"); }
  }
  return g.map((r) => r.join(""));
};

