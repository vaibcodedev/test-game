/**
 * Склонения в T(): {n:предмет|предмета|предметов} через Intl.PluralRules (shared/texts.ts).
 * Запуск: npx tsx tests/unit/texts-plural.ts
 */
import { plural, T } from "../../shared/texts";
import { assert, done, section, test } from "./lib";

section("plural");
const f = (n: number) => plural(n, "предмет", "предмета", "предметов");
await test("формы", () => {
  for (const [n, w] of [[0, "предметов"], [1, "предмет"], [2, "предмета"], [4, "предмета"], [5, "предметов"], [11, "предметов"], [12, "предметов"],
    [21, "предмет"], [22, "предмета"], [25, "предметов"], [101, "предмет"], [111, "предметов"], [1.5, "предмета"], [-1, "предмет"]] as const)
    assert.equal(f(n), w, String(n));
});
await test("T: разбор в тексте, число — отдельно", () => {
  // ключа нет — возвращается сам ключ как шаблон
  assert.equal(T("{n} {n:предмет|предмета|предметов}!", { n: 3 }), "3 предмета!");
  assert.equal(T("{n} {n:героя|героев|героев}", { n: "1" }), "1 героя");
  assert.equal(T("{n:а|б|в} {x}", { n: 5, x: "ок" }), "в ок");
});
await test("T: нет переменной или не число — шаблон остаётся", () => {
  assert.equal(T("{n:а|б|в}", { k: 1 }), "{n:а|б|в}");
  assert.equal(T("{n:а|б|в}", { n: "abc" }), "{n:а|б|в}");
  assert.equal(T("{n:а|б|в}"), "{n:а|б|в}");
});
done();
